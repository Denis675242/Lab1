-- Вариант 17. База данных Lab1

CREATE TABLE disciplines (
    discipline_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discipline_name VARCHAR(100) NOT NULL,
    description     TEXT,
    standard_year   INT NOT NULL
);

CREATE TABLE workload (
    teacher_id    INT NOT NULL,
    discipline_id INT NOT NULL,
    hour_cost     NUMERIC(10,2) NOT NULL CHECK (hour_cost >= 0),
    hourly_pay    NUMERIC(10,2) NOT NULL CHECK (hourly_pay >= 0),
    PRIMARY KEY (teacher_id, discipline_id),
    FOREIGN KEY (discipline_id) REFERENCES disciplines(discipline_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);
